import ModelCatalog
import SwiftUI
import UnalomeDesign

/// App name and version, the privacy statement, links, and every licence the app ships under.
struct AboutView: View {
    let services: AppServices

    @State private var isRevealed = false

    static let privacyStatement = """
        Unalome Pocket runs language models entirely on this device. There is no account, no \
        analytics and no telemetry: your messages, images, voice and chats are processed and \
        stored only here. The only time the app uses the network is to download a model you \
        choose, from huggingface.co. Reporting a response opens an email in your mail app; \
        nothing is sent unless you send it.
        """

    static let aiNotice = """
        Replies are generated by a small language model running on your device. They can be \
        wrong, out of date or offensive. Check anything important, and use "Report this response" \
        on a reply to tell us about a problem.
        """

    var body: some View {
        List {
            Section {
                header
                    .listRowBackground(Color.clear)
                    .frame(maxWidth: .infinity)
            }

            Section("Privacy") {
                Text(Self.privacyStatement)
                    .unalomeText(.callout)
                    .foregroundStyle(UnalomeColor.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)
            }

            Section("AI-generated replies") {
                Text(Self.aiNotice)
                    .unalomeText(.callout)
                    .foregroundStyle(UnalomeColor.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)
            }

            Section {
                LinkRow(title: "unalome.ai", systemImage: "globe", url: AppLinks.website)
                LinkRow(title: "Source code", systemImage: "chevron.left.forwardslash.chevron.right", url: AppLinks.sourceCode)
                if let url = URL(string: "mailto:\(AppLinks.supportEmail)") {
                    LinkRow(title: "Contact support", systemImage: "envelope", url: url)
                        .accessibilityHint("Opens an email to \(AppLinks.supportEmail)")
                }
            }

            Section {
                ForEach(modelLicenses, id: \.name) { model in
                    LicenseRow(name: model.name, licence: model.licence, url: model.url)
                }
            } header: {
                Text("Model licences")
            } footer: {
                Text("Each model is downloaded only after you accept its licence.")
            }

            Section {
                ForEach(OpenSourceComponent.all) { component in
                    LicenseRow(
                        name: component.version.isEmpty ? component.name : "\(component.name) \(component.version)",
                        licence: component.licence,
                        url: component.url)
                }
            } header: {
                Text("Open-source software")
            } footer: {
                Text("Unalome Pocket is built with these packages and the Inter typeface.")
            }
        }
        .scrollContentBackground(.hidden)
        .background(GlowBackdrop())
        .navigationTitle("About")
        #if os(iOS)
        .navigationBarTitleDisplayMode(.inline)
        #endif
        .onAppear { isRevealed = true }
    }

    private var header: some View {
        VStack(spacing: 14) {
            UnalomeMark(height: 64)
                .revealed(isRevealed)
            VStack(spacing: 4) {
                Text("Unalome Pocket")
                    .unalomeText(.title)
                    .foregroundStyle(UnalomeColor.textPrimary)
                Text(Self.versionText)
                    .unalomeText(.footnote)
                    .foregroundStyle(UnalomeColor.textTertiary)
            }
            .revealed(isRevealed, delay: 0.15)
            .accessibilityElement(children: .combine)
        }
        .padding(.vertical, 16)
    }

    static var versionText: String {
        "Version \(AppVersion.marketing) (build \(AppVersion.build))"
    }

    /// Catalog models plus anything installed from outside the catalog.
    private var modelLicenses: [(name: String, licence: String, url: URL?)] {
        let library = services.library
        let installedIDs = Set(library.installed.map(\.repoID))
        var rows = (library.catalog.models + library.addedEntries).map {
            (name: $0.displayName,
             licence: installedIDs.contains($0.id) ? "\($0.license.name) · installed" : $0.license.name,
             url: $0.license.url)
        }
        for model in library.installed where !rows.contains(where: { $0.name == model.displayName }) {
            rows.append((name: model.displayName, licence: "\(model.licenseName) · installed", url: model.licenseURL))
        }
        return rows
    }
}

/// A link in the app's own colours. On Mac, `Link` otherwise uses the system link colour and the
/// icons the system accent colour, which the user may have set to anything.
private struct LinkRow: View {
    let title: String
    let systemImage: String
    let url: URL

    var body: some View {
        Link(destination: url) {
            Label {
                Text(title).foregroundStyle(UnalomeColor.textPrimary)
            } icon: {
                Image(systemName: systemImage).foregroundStyle(UnalomeColor.emerald)
            }
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
    }
}

private struct LicenseRow: View {
    let name: String
    let licence: String
    let url: URL?

    var body: some View {
        let content = VStack(alignment: .leading, spacing: 2) {
            Text(name)
                .unalomeText(.body)
                .foregroundStyle(UnalomeColor.textPrimary)
            Text(licence)
                .unalomeText(.footnote)
                .foregroundStyle(UnalomeColor.textSecondary)
        }
        if let url {
            Link(destination: url) {
                HStack {
                    content
                    Spacer()
                    Image(systemName: "arrow.up.right")
                        .imageScale(.small)
                        .foregroundStyle(UnalomeColor.textTertiary)
                }
            }
            .buttonStyle(.plain)
            .accessibilityHint("Opens the licence")
        } else {
            content
        }
    }
}

/// Every resolved package dependency (Package.resolved) and bundled asset, with its licence
/// as stated in its LICENSE file.
